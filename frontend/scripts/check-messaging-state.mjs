import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import ts from "typescript";

const compile = (s) => ts.transpileModule(s, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 } }).outputText;
const url = (s) => `data:text/javascript;base64,${Buffer.from(s).toString("base64")}`;
const utility = url(compile(await readFile(new URL("../src/lib/api.ts", import.meta.url), "utf8")));
const adapter = url(compile(await readFile(new URL("../src/features/messaging/api.ts", import.meta.url), "utf8")).replace('"@/lib/api"', JSON.stringify(utility)));
const notifications = url(compile(await readFile(new URL("../src/features/messaging/notifications.ts", import.meta.url), "utf8")));
const controller = url(compile(await readFile(new URL("../src/features/messaging/use-messaging.ts", import.meta.url), "utf8")).replace('"./api"', JSON.stringify(adapter)).replace('"./notifications"', JSON.stringify(notifications)).replace('"react"', JSON.stringify(import.meta.resolve("react"))));
const { mergeMessages } = await import(controller);
const { messageView, parseLiveEvent, websocketUrl } = await import(adapter);
const { filterInbox, shouldNotifyIncoming } = await import(notifications);
const sender = { id: "alex-id", display_name: "Alex", username: "alex", phone_e164: null, avatar_url: null, online: true, last_seen_at: null };
const first = { id: "one", sequence: 1, client_message_id: "stable-client-id", kind: "text", body: "Hello", created_at: "2026-10-09T07:00:00Z", sender, receipt: "sent" };
const second = { ...first, id: "two", sequence: 2, client_message_id: "second-client-id" };
const deliveredByEvent = messageView({ ...first, receipt: "read" }, sender.id);
const oldSnapshot = [messageView(second, sender.id), messageView(first, sender.id)];
const recovered = mergeMessages([deliveredByEvent], oldSnapshot);
assert.deepEqual(recovered.map((m) => m.id), ["one", "two"]);
assert.equal(recovered[0].receipt, "read");
assert.equal(recovered[0].clientId, "stable-client-id");
assert.equal(messageView(first, "maya-id").outgoing, false);
assert.equal(messageView(first, "alex-id").outgoing, true);
assert.equal(mergeMessages(recovered, [deliveredByEvent]).length, 2);
assert.throws(() => parseLiveEvent({ type: "typing.updated", payload: { user_id: "x", name: "Maya", is_typing: "yes" } }));
const groupConversation = { id: "group-id", kind: "group", title: "Review group", avatar_url: null, other_user: null, last_activity_at: first.created_at, unread_count: 0, latest_message: null };
assert.equal(parseLiveEvent({ type: "group.created", event_id: 12, payload: { conversation: groupConversation, messages: [] } }).conversation.id, "group-id");
assert.equal(parseLiveEvent({ type: "group.members_updated", event_id: 13, payload: { conversation: groupConversation, messages: [first] } }).messages.length, 1);
assert.equal(parseLiveEvent({ type: "conversation.access_revoked", event_id: 14, payload: { conversation_id: "group-id" } }).conversationId, "group-id");
assert.throws(() => parseLiveEvent({ type: "conversation.access_revoked", payload: {} }));
assert.deepEqual(filterInbox([groupConversation, { ...groupConversation, id: "unread", unread_count: 2 }], "unread").map((c) => c.id), ["unread"]);
assert.equal(filterInbox([groupConversation], "all").length, 1);
const seen = new Set();
assert.equal(shouldNotifyIncoming(first, "maya-id", false, true, seen), true);
assert.equal(shouldNotifyIncoming(first, "maya-id", false, true, seen), false);
assert.equal(shouldNotifyIncoming({ ...first, id: "own" }, "alex-id", false, true, seen), false);
assert.equal(shouldNotifyIncoming({ ...first, id: "reading" }, "maya-id", true, true, seen), false);
assert.equal(shouldNotifyIncoming({ ...first, id: "replay" }, "maya-id", false, false, seen), false);
assert.equal(shouldNotifyIncoming({ ...first, id: "system", kind: "system", sender: null }, "maya-id", false, true, seen), false);
console.log("PASS: real-data unread filtering; incoming notification deduplication; suppression while reading, for own/system messages and replay.");
const original = process.env.NEXT_PUBLIC_API_URL;
const originalWs = process.env.NEXT_PUBLIC_WS_URL;
delete process.env.NEXT_PUBLIC_WS_URL;
process.env.NEXT_PUBLIC_API_URL = "https://example.test";
assert.equal(websocketUrl(17), "wss://example.test/api/v1/ws?cursor=17");
process.env.NEXT_PUBLIC_API_URL = "same-origin";
globalThis.window = { location: { origin: "https://single-origin.example.test" } };
assert.equal(websocketUrl(18), "wss://single-origin.example.test/api/v1/ws?cursor=18");
globalThis.window.location.origin = "http://localhost:18080";
assert.equal(websocketUrl(19), "ws://localhost:18080/api/v1/ws?cursor=19");
delete globalThis.window;
process.env.NEXT_PUBLIC_API_URL = original;
if (originalWs !== undefined) process.env.NEXT_PUBLIC_WS_URL = originalWs;
console.log("PASS: out-of-order snapshots/events merge once in sequence; read receipts do not regress; stable client IDs/alignment and HTTPS→WSS derivation are preserved.");
console.log("These are state/contract checks, not browser interaction tests.");
